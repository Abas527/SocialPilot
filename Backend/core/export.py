import json
import shutil
import subprocess
import tempfile
from datetime import date
from pathlib import Path

from core.schemas import CaseStudy

TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "case_study.typ"
SECTIONS = [("Problem and Motivation", "problem"), ("Architecture and Technologies", "architecture"),
            ("Implementation Decisions", "implementation"), ("Engineering Challenges", "challenges"),
            ("Results and Evaluation", "results"), ("Limitations", "limitations"), ("Future Work", "future_work")]


class ExportError(RuntimeError):
    pass


def case_study_to_markdown(cs: CaseStudy, repo_url: str | None = None) -> str:
    out = [f"# {cs.title}", "", cs.summary, ""]
    for heading, attr in SECTIONS:
        out += [f"## {heading}", "", getattr(cs, attr) or "_Not documented._", ""]
    if repo_url:
        out += ["## Repository", "", repo_url, ""]
    return "\n".join(out)


def build_typst_data(cs: CaseStudy, repo_url: str | None = None) -> dict:
    meta = f"Generated {date.today().isoformat()}" + (f" \u2022 {repo_url}" if repo_url else "")
    return {
        "title": cs.title, "meta": meta,
        "footer": "Generated by SocialPilot AI \u2013 not independently verified",
        "sections": [{"heading": "Summary", "body": cs.summary}]
        + [{"heading": h, "body": getattr(cs, a) or "Not documented."} for h, a in SECTIONS],
    }


def export_pdf(cs: CaseStudy, repo_url: str | None = None, timeout_s: int = 30) -> bytes:
    if not shutil.which("typst"):
        raise ExportError("Typst is not installed or not on PATH. PDF export is unavailable; use Markdown export.")
    with tempfile.TemporaryDirectory() as tmp:
        tmp_p = Path(tmp)
        (tmp_p / "data.json").write_text(json.dumps(build_typst_data(cs, repo_url)), encoding="utf-8")
        shutil.copy(TEMPLATE, tmp_p / "case_study.typ")
        try:
            r = subprocess.run(["typst", "compile", "case_study.typ", "out.pdf"], cwd=tmp, capture_output=True,
                               text=True, timeout=timeout_s)
        except subprocess.TimeoutExpired as e:
            raise ExportError("Typst compilation timed out.") from e
        pdf = tmp_p / "out.pdf"
        if r.returncode != 0 or not pdf.exists():
            raise ExportError(f"Typst failed: {r.stderr[:500]}")
        return pdf.read_bytes()
